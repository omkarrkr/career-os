import { expect, test } from '@playwright/test';
import { startFixtureSuite } from './fixture';
test.beforeAll(async ({ request }) => { await startFixtureSuite(request); });
test.beforeEach(async ({ context, baseURL }) => {
  const allowed = new URL(baseURL!).origin;
  await context.route('**/api/**', route => new URL(route.request().url()).origin === allowed ? route.continue() : route.abort());
});
test('priority and subtasks: persisted controls, independent completion, draft guards, failures and pagination', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/login'); await page.getByLabel('Email address', { exact: true }).fill('ui-student@example.test');
  await page.getByLabel('Password', { exact: true }).fill('Fictional browser test passphrase!');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Your next steps start here.' })).toBeVisible();
  await page.goto('/goals/new'); await page.getByLabel('Title', { exact: true }).fill('Fictional execution goal');
  await page.getByLabel('Category', { exact: true }).fill('Projects'); await page.getByLabel('Priority', { exact: true }).selectOption('HIGH');
  await page.getByRole('button', { name: 'Create goal', exact: true }).click();
  await expect(page.getByText('Priority: High', { exact: true })).toBeVisible();
  const goalId = page.url().split('/').at(-1)!;
  const panel = page.getByRole('region', { name: 'Subtasks', exact: true });
  const add = async (title: string) => { await panel.getByLabel('New subtask', { exact: true }).fill(title); await panel.getByRole('button', { name: 'Add subtask', exact: true }).click(); await expect(panel.getByRole('checkbox', { name: title, exact: true })).toBeVisible(); };
  await add('Write About page'); await add('Add screenshots');
  await panel.getByRole('checkbox', { name: 'Write About page', exact: true }).click();
  await expect(panel.getByRole('checkbox', { name: 'Write About page', exact: true })).toBeChecked();
  await expect(panel.getByText('1 of 2 subtasks completed', { exact: true })).toBeVisible();
  await expect(page.locator('.goal-detail > .goal-status')).toHaveText('Active');
  await panel.getByRole('button', { name: 'Rename subtask: Write About page', exact: true }).click();
  await panel.getByLabel('Subtask title', { exact: true }).fill('Publish About page');
  await panel.getByRole('button', { name: 'Save subtask', exact: true }).click();
  await expect(panel.getByRole('checkbox', { name: 'Publish About page', exact: true })).toBeChecked();
  await page.reload(); await expect(panel.getByRole('checkbox', { name: 'Publish About page', exact: true })).toBeChecked();
  await page.getByRole('button', { name: 'Edit goal', exact: true }).click();
  await page.getByLabel('Priority', { exact: true }).selectOption('LOW'); await page.getByRole('button', { name: 'Save goal', exact: true }).click();
  await expect(page.getByText('Priority: Low', { exact: true })).toBeVisible();
  await panel.getByLabel('New subtask', { exact: true }).fill('Keep local draft');
  await expect(page.getByRole('button', { name: 'Delete goal', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Edit goal', exact: true })).toBeDisabled();
  const cancelled = new Promise<void>(resolve => page.once('dialog', async dialog => { await dialog.dismiss(); resolve(); }));
  await page.getByRole('link', { name: 'Back to goals', exact: true }).click(); await cancelled;
  await expect(panel.getByLabel('New subtask', { exact: true })).toHaveValue('Keep local draft');
  const discard = new Promise<void>(resolve => page.once('dialog', async dialog => { await dialog.accept(); resolve(); }));
  await panel.getByRole('button', { name: 'Discard draft', exact: true }).click(); await discard;
  const cancelDelete = new Promise<void>(resolve => page.once('dialog', async dialog => { await dialog.dismiss(); resolve(); }));
  await panel.getByRole('button', { name: 'Delete subtask: Publish About page', exact: true }).click(); await cancelDelete;
  await expect(panel.getByRole('checkbox', { name: 'Publish About page', exact: true })).toBeVisible();
  const confirmDelete = new Promise<void>(resolve => page.once('dialog', async dialog => { await dialog.accept(); resolve(); }));
  await panel.getByRole('button', { name: 'Delete subtask: Publish About page', exact: true }).click(); await confirmDelete;
  await expect(panel.getByText('0 of 1 subtasks completed', { exact: true })).toBeVisible();
  await panel.getByRole('checkbox', { name: 'Add screenshots', exact: true }).click();
  await expect(panel.getByRole('checkbox', { name: 'Add screenshots', exact: true })).toBeChecked();
  await expect(panel.getByText('1 of 1 subtasks completed', { exact: true })).toBeVisible();
  await expect(page.locator('.goal-detail > .goal-status')).toHaveText('Active');
  await page.getByRole('button', { name: 'Mark completed', exact: true }).click();
  await expect(page.locator('.goal-detail > .goal-status')).toHaveText('Completed');
  await add('Review finished result');
  const createPattern = `**/api/goals/${goalId}/subtasks`;
  await page.route(createPattern, route => route.request().method() === 'POST' ? route.fulfill({ status: 500, json: { message: 'Temporary failure' } }) : route.continue());
  await panel.getByLabel('New subtask', { exact: true }).fill('Keep failed draft');
  await panel.getByRole('button', { name: 'Add subtask', exact: true }).click();
  await expect(panel.getByRole('alert')).toContainText('Reload saved subtasks');
  await expect(panel.getByLabel('New subtask', { exact: true })).toHaveValue('Keep failed draft');
  await expect(panel.getByRole('button', { name: 'Add subtask', exact: true })).toBeDisabled();
  await panel.getByRole('button', { name: 'Reload subtasks', exact: true }).click();
  await expect(panel.getByRole('status')).toContainText('Saved subtasks reloaded');
  await page.unroute(createPattern); await panel.getByRole('button', { name: 'Add subtask', exact: true }).click();
  await expect(panel.getByRole('checkbox', { name: 'Keep failed draft', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.route(`**/api/goals/${goalId}/subtasks?*`, route => {
    const more = new URL(route.request().url()).searchParams.has('afterId');
    const row = (id: number) => ({ id, goalId: Number(goalId), title: `Paged step ${id}`, isCompleted: id <= 7, createdAt: '2026-01-01', updatedAt: '2026-01-01' });
    return route.fulfill({ json: { data: more ? [row(21)] : Array.from({ length: 20 }, (_, i) => row(i+1)), nextCursor: more ? null : 20, summary: { total: 21, completed: 7 } } });
  });
  await page.reload(); await expect(panel.getByText('7 of 21 subtasks completed', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Load more subtasks', exact: true }).click();
  await expect(panel.getByRole('checkbox', { name: 'Paged step 21', exact: true })).toBeVisible();
  await expect(panel.getByText('7 of 21 subtasks completed', { exact: true })).toBeVisible();
  await panel.getByRole('button', { name: 'Rename subtask: Paged step 21', exact: true }).click();
  await panel.getByLabel('Subtask title', { exact: true }).fill('Preserve a removed step draft');
  await page.unroute(`**/api/goals/${goalId}/subtasks?*`);
  await page.route(`**/api/goals/${goalId}/subtasks?*`, route => route.fulfill({ json: { data: [], nextCursor: null, summary: { total: 0, completed: 0 } } }));
  await panel.getByRole('button', { name: 'Reload subtasks', exact: true }).click();
  await expect(panel.getByLabel('Unmatched subtask draft', { exact: true })).toHaveValue('Preserve a removed step draft');
  const discardMissing = new Promise<void>(resolve => page.once('dialog', async dialog => { await dialog.accept(); resolve(); }));
  await panel.getByRole('button', { name: 'Discard missing subtask draft', exact: true }).click(); await discardMissing;
  await expect(panel.getByLabel('New subtask', { exact: true })).toBeEnabled();
});
